    private void drawInfo(DrawContext ctx, int mouseX, int mouseY) {
        List<String> lines = new ArrayList<>();
        if (!status.isEmpty()) lines.add(status);
        else if (world == null) lines.add(seedText.isEmpty() ? "Type a seed and press Load" : "Loading...");
        if (mouseY > TOP) {
            int x = (int) Math.floor(wx(mouseX)), z = (int) Math.floor(wz(mouseY));
            String biome = biomeAtCursor(x, z);
            lines.add(x + ", " + z + (biome != null ? "  " + biome : ""));
        }
        String zoom = bpp >= 1 ? String.format("1 px = %.0f blocks", bpp) : String.format("%.1f px per block", 1 / bpp);
        int pending = pendingTiles.size() + pendingStructures.size();
        lines.add(zoom + (pending > 0 ? "  (generating " + pending + ")" : "") + "   Drag: move  Scroll: zoom  Right-click: destination");
        int y = height - 6 - lines.size() * 11;
        int w = 0;
        for (String l : lines) w = Math.max(w, ui.width(l));
        Render2D.roundedRect(ctx, 6, y - 4, w + 12, lines.size() * 11 + 6, 5, 0xE0121318);
        for (String l : lines) {
            ui.text(l, 12, y, Theme.TEXT);
            y += 11;
        }
    }

    /** Biome name under the cursor, read from the already generated tile (no sampling on the render thread). */
    private String biomeAtCursor(int x, int z) {
        int shift = cellShift(), cell = 1 << shift, tileBlocks = cell * TILE;
        int tx = Math.floorDiv(x, tileBlocks), tz = Math.floorDiv(z, tileBlocks);
        Tile tile = tiles.get(tileKey(shift, tx, tz));
        if (tile == null) return null;
        int c = Math.floorDiv(x - tx * tileBlocks, cell), r = Math.floorDiv(z - tz * tileBlocks, cell);
        if (c < 0 || c >= TILE || r < 0 || r >= TILE) return null;
        int index = tile.biomes[r * TILE + c];
        synchronized (biomePalette) {
            return index < biomePalette.size() ? BiomeColors.pretty(biomePalette.get(index)) : null;
        }
    }

    // ------------------------------------------------------------------ input

    @Override
    protected boolean onMouseClick(double mouseX, double mouseY, int button) {
        ui.dispatchClick(mouseX, mouseY, button);
        return true;
    }

    @Override
    protected void onMouseRelease(double mouseX, double mouseY, int button) {
        ui.drag = null;
    }

    @Override
    protected void onMouseDrag(double mouseX, double mouseY, int button) {
        if (ui.drag != null) ui.drag.onDrag(mouseX, mouseY);
    }

    @Override
    protected boolean onScroll(double mouseX, double mouseY, double amount) {
        if (mouseY < TOP) return true;
        double beforeX = wx(mouseX), beforeZ = wz(mouseY);
        bpp = Math.max(0.25, Math.min(256, bpp * (amount > 0 ? 1 / 1.25 : 1.25)));
        centerX = beforeX - (mouseX - cx()) * bpp;
        centerZ = beforeZ - (mouseY - cy()) * bpp;
        return true;
    }

    @Override
    protected boolean onKey(int key, int scancode, int modifiers) {
        if (ui.focused != null) {
            if (key == org.lwjgl.glfw.GLFW.GLFW_KEY_ESCAPE) {
                ui.focused = null;
                return true;
            }
            return ui.focused.keyPressed(key, modifiers);
        }
        return false;
    }

    @Override
    protected boolean onChar(int codepoint) {
        return ui.focused != null && ui.focused.charTyped(codepoint);
    }
